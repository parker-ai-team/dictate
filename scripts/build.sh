#!/bin/zsh
# Builds Dictate.app with swiftc (no Xcode project, no SwiftPM) and installs it
# to ~/Applications/Dictate.app.
#
#   scripts/build.sh                 build + install + relaunch
#   scripts/build.sh --no-install    build only (build/Dictate.app)
#   scripts/build.sh --no-launch     build + install, do not relaunch
#   scripts/build.sh --debug ...     also compile the --insert / --hotkey-test
#                                    headless modes (never for a daily build:
#                                    they let any local process paste through
#                                    the app's Accessibility grant)
#
# Environment overrides:
#   DICTATE_BUNDLE_ID       default com.parkeraiteam.dictate
#   DICTATE_SIGN_IDENTITY   a code-signing identity name; default ad-hoc ("-")
#   DICTATE_SIGN_KEYCHAIN   keychain file holding that identity (optional)
#
# Requirements: Apple Silicon Mac, macOS 13 or later, Xcode or the Command
# Line Tools (xcode-select --install).
set -euo pipefail
cd "$(dirname "$0")/.."

APP_NAME=Dictate
BUNDLE_ID="${DICTATE_BUNDLE_ID:-com.parkeraiteam.dictate}"
VERSION=$(grep -o 'appVersion = "[^"]*"' Sources/Config.swift | cut -d'"' -f2)
BUILD=build
OUT_APP="$BUILD/$APP_NAME.app"
INSTALL_DIR="$HOME/Applications"
SIGN_IDENTITY="${DICTATE_SIGN_IDENTITY:--}"
SIGN_KEYCHAIN="${DICTATE_SIGN_KEYCHAIN:-}"

mkdir -p "$BUILD"

# --- compiler flags ------------------------------------------------------
EXTRA_FLAGS=()
if [[ "${1:-}" == "--debug" ]]; then
  EXTRA_FLAGS+=(-D DICTATE_DEBUG)
  echo "==> DEBUG build: headless --insert / --hotkey-test compiled in"
  shift
fi
# Some Command Line Tools installs carry a leftover usr/include/swift/module.modulemap
# next to bridging.modulemap; both define module SwiftBridging and every
# `import Foundation` fails with "redefinition of module 'SwiftBridging'".
# If both files exist, blank the stale one for the compiler only (a clang
# virtual-file-system overlay; nothing on disk changes). Healthy toolchains
# never hit this branch.
CLT_SWIFT_INC="/Library/Developer/CommandLineTools/usr/include/swift"
if [[ -f "$CLT_SWIFT_INC/module.modulemap" && -f "$CLT_SWIFT_INC/bridging.modulemap" ]]; then
  : > "$BUILD/empty.modulemap"
  cat > "$BUILD/overlay.yaml" <<EOF
{ "version": 0, "roots": [ { "type": "file",
  "name": "$CLT_SWIFT_INC/module.modulemap",
  "external-contents": "$PWD/$BUILD/empty.modulemap" } ] }
EOF
  EXTRA_FLAGS+=(-vfsoverlay "$PWD/$BUILD/overlay.yaml")
  echo "==> note: duplicate SwiftBridging module map in Command Line Tools, applying compiler overlay"
fi

echo "==> compiling (swiftc, release)"
swiftc -O -swift-version 5 \
  -target arm64-apple-macos13.0 \
  "${EXTRA_FLAGS[@]}" \
  -module-name "$APP_NAME" \
  -framework AppKit -framework AVFoundation -framework SwiftUI -framework ServiceManagement \
  Sources/*.swift \
  -o "$BUILD/$APP_NAME"

echo "==> assembling bundle"
mkdir -p "$OUT_APP/Contents/MacOS" "$OUT_APP/Contents/Resources"
cp "$BUILD/$APP_NAME" "$OUT_APP/Contents/MacOS/$APP_NAME"
printf 'APPL????' > "$OUT_APP/Contents/PkgInfo"
# Icon assets are generated by scripts/make-icon.sh from Icon/*.svg and kept in Resources/.
for f in AppIcon.icns MenuBarTemplate.png MenuBarTemplate@2x.png; do
  [[ -f "Resources/$f" ]] && cp "Resources/$f" "$OUT_APP/Contents/Resources/$f"
done
cat > "$OUT_APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleExecutable</key><string>$APP_NAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSUIElement</key><true/>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSMicrophoneUsageDescription</key>
  <string>Dictate records your voice while you hold the hotkey and transcribes it on this Mac.</string>
  <key>NSHumanReadableCopyright</key><string>MIT License, Parker AI Team</string>
</dict>
</plist>
EOF

# --- signing -------------------------------------------------------------
# Ad-hoc by default. It works, but macOS ties the Microphone and Accessibility
# grants to the signature, and an ad-hoc signature changes with every build,
# so after a rebuild you re-enable Dictate under Accessibility. For a stable
# signature use your own Apple Development identity, or create a free
# self-signed one with scripts/make-signing-cert.sh and export
# DICTATE_SIGN_IDENTITY="Dictate Dev". Each codesign call runs under a 60 s
# alarm so a keychain dialog can never hang the build.
sign_app() {
  local target="$1"
  local kc_args=()
  if [[ "$SIGN_IDENTITY" != "-" ]]; then
    if [[ -n "$SIGN_KEYCHAIN" ]]; then
      local pw
      pw="$(security find-generic-password -s "$BUNDLE_ID.signing" -a keychain -w 2>/dev/null || true)"
      [[ -n "$pw" ]] && security unlock-keychain -p "$pw" "$SIGN_KEYCHAIN"
      kc_args=(--keychain "$SIGN_KEYCHAIN")
    fi
    echo "==> signing $target with identity: $SIGN_IDENTITY"
    perl -e 'alarm 60; exec @ARGV' codesign --force --sign "$SIGN_IDENTITY" "${kc_args[@]}" \
      --identifier "$BUNDLE_ID" --timestamp=none "$target"
  else
    echo "==> signing $target ad-hoc"
    codesign --force --sign - --identifier "$BUNDLE_ID" "$target"
  fi
}
sign_app "$OUT_APP"
codesign --verify --strict "$OUT_APP" && echo "==> signature ok"

if [[ "${1:-}" == "--no-install" ]]; then
  echo "==> built $OUT_APP (not installed)"
  exit 0
fi

# --- install -------------------------------------------------------------
mkdir -p "$INSTALL_DIR"
if pgrep -x "$APP_NAME" >/dev/null; then
  echo "==> quitting running $APP_NAME (clean quit so it stops its whisper-server)"
  osascript -e "tell application id \"$BUNDLE_ID\" to quit" >/dev/null 2>&1 || true
  for i in 1 2 3 4 5; do pgrep -x "$APP_NAME" >/dev/null || break; sleep 1; done
  pgrep -x "$APP_NAME" >/dev/null && pkill -x "$APP_NAME" || true
  sleep 1
fi
# ditto overwrites the files inside an existing bundle in place.
ditto "$OUT_APP" "$INSTALL_DIR/$APP_NAME.app"
sign_app "$INSTALL_DIR/$APP_NAME.app"
echo "==> installed $INSTALL_DIR/$APP_NAME.app"
touch "$INSTALL_DIR/$APP_NAME.app"   # nudges Finder to re-read the icon
if [[ "${1:-}" != "--no-launch" ]]; then
  open "$INSTALL_DIR/$APP_NAME.app"
  echo "==> relaunched $APP_NAME"
fi
